// Lists every picture under assets/game so Metro bundles it (require needs static paths). Run after adding or removing pictures:
//   node scripts/gen-assets.mjs
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "assets", "game");
const files = [];
const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else if (/\.(webp|png)$/.test(n)) files.push(relative(dir, p).split("\\").join("/")); } };
walk(dir);
files.sort();
writeFileSync(join(root, "src", "generated", "assetModules.ts"),
  `// Generated by scripts/gen-assets.mjs — do not edit.\nexport const ASSET_MODULES: Record<string, number> = {\n${files.map((f) => `  "assets/${f}": require("../../assets/game/${f}"),`).join("\n")}\n};\n`);
console.log(`${files.length} pictures listed`);
