// Packs the web game (../bakery-street) for the app:
//   - bundles src/main.js into one classic script (a WebView loading file:// pages cannot load ES modules),
//   - rewrites index.html to use it, and
//   - copies the pictures into game-assets/ and writes src/generated/game.ts, which lists every file for Metro (require) and
//     carries the three text files as strings. The app copies them to disk on first launch and opens index.html from there.
// Run by `npm run build:game`, and automatically on EAS (`eas-build-post-install`). Everything it writes is git-ignored.
import { build } from "esbuild";
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const game = join(root, "..", "bakery-street");
const out = join(root, "game-assets");
const gen = join(root, "src", "generated");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
mkdirSync(gen, { recursive: true });

// 1. the script
const js = await build({
  entryPoints: [join(game, "src", "main.js")],
  bundle: true,
  format: "iife",
  minify: true,
  target: "safari15",
  write: false,
  logLevel: "warning",
});
const gameJs = js.outputFiles[0].text;

// 2. the page: no manifest/icons (the app has its own), the module script becomes the bundle
let html = readFileSync(join(game, "index.html"), "utf8");
html = html
  .replace(/\s*<link rel="(?:icon|apple-touch-icon|manifest)"[^>]*>/g, "")
  .replace(/<script type="module" src="src\/main\.js"><\/script>/, '<script src="game.js"></script>');
if (!html.includes('src="game.js"')) throw new Error("index.html: the module script tag was not found");
const css = readFileSync(join(game, "style.css"), "utf8");

// 3. the pictures (the app icon set is not needed in the page except the loading logo)
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else {
      const rel = relative(game, p).split("\\").join("/");
      if (rel.startsWith("assets/app/") && rel !== "assets/app/logo.webp") continue;
      if (/\.(webp|png|jpg|jpeg|svg)$/.test(rel)) files.push(rel);
    }
  }
};
walk(join(game, "assets"));
files.sort();
for (const rel of files) {
  mkdirSync(dirname(join(out, rel)), { recursive: true });
  cpSync(join(game, rel), join(out, rel));
}

const ts = `// Generated by scripts/build-game.mjs — do not edit.
export const GAME_VERSION = ${JSON.stringify(Date.now().toString(36))};
export const TEXT_FILES: Record<string, string> = {
  "index.html": ${JSON.stringify(html)},
  "style.css": ${JSON.stringify(css)},
  "game.js": ${JSON.stringify(gameJs)},
};
export const PICTURES: Record<string, number> = {
${files.map((f) => `  ${JSON.stringify(f)}: require("../../game-assets/${f}"),`).join("\n")}
};
`;
writeFileSync(join(gen, "game.ts"), ts);
console.log(`game packed: ${files.length} pictures, game.js ${(gameJs.length / 1024).toFixed(0)} KB`);
